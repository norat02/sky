-- Supabase Auth cung cấp auth.users; các bảng game chỉ được API server truy cập bằng service_role.
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 10),
  score integer not null check (score between 0 and 100000),
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.score_runs (
  run_id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  started_at timestamptz not null default now(),
  submitted_at timestamptz
);

create index if not exists scores_score_created_idx on public.scores (score desc, created_at asc);
create index if not exists score_runs_user_started_idx on public.score_runs (user_id, started_at desc);
create index if not exists score_runs_open_idx on public.score_runs (run_id, user_id) where submitted_at is null;

alter table public.scores enable row level security;
alter table public.score_runs enable row level security;

